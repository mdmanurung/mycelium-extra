"""Print the ask-extra router table, grouped by situation, from the skills' own descriptions.

Read-only. Run from stdin so Mycelium's hooks stay closed:

    sh <skill-dir>/../../hooks/py.sh - --repo . < <skill-dir>/scripts/make_router_table.py
    sh <skill-dir>/../../hooks/py.sh - --repo . --check <skill-dir>/references/router-table.md < <skill-dir>/scripts/make_router_table.py

Reads skills/*/SKILL.md frontmatter. Every user-invoked skill (disable-model-invocation: true)
is listed. A user-invoked skill the group map does not know goes under "Other" and is
reported on stderr. A name in the map with no folder is skipped and reported on stderr.
Exit 0: printed, or --check matched. Exit 1: --check found a difference. Exit 2: no skills found.
"""

import argparse
import glob
import os
import re
import sys

# Groups in the order a bioinformatician meets them. A skill may sit in two groups.
# Model-invoked skills (grill, verify, plot-first, track-changes, manuscript-audit) are named
# because the human still types them; their rows come from their own descriptions too.
GROUPS = [
    ("I lost track", ["where", "focus", "re-pitch", "handoff", "handoff-resume"]),
    (
        "I am starting something",
        ["new-analysis", "grill", "analysis-map", "research-note", "glossary", "questionnaire", "setup-wizard", "repo-setup", "init", "idea-triage"],
    ),
    ("I am exploring", ["prototype-analysis", "plot-first", "check-first"]),
    ("Something looks wrong", ["diagnose-result", "verify", "track-changes"]),
    ("I want to report", ["analysis-report", "verify", "manuscript-audit"]),
    ("I want the structure cleaner", ["improve-structure", "skill-style", "harden"]),
]

# Typed words the gate answers, shown instead of the slash form.
TYPED = {
    "where": "`where` or `/mycelium-extra:where`",
    "focus": "`focus <folder>`",
}

OTHER = "Other"
ROUTER = "ask-extra"


def frontmatter(text):
    parts = text.split("---", 2)
    return parts[1] if len(parts) > 2 else ""


def read_skills(repo):
    """Return {name: {'user': bool, 'description': str}} for every skills/*/SKILL.md."""
    found = {}
    for path in sorted(glob.glob(os.path.join(repo, "skills", "*", "SKILL.md"))):
        name = os.path.basename(os.path.dirname(path))
        with open(path, encoding="utf-8") as handle:
            fm = frontmatter(handle.read())
        user = re.search(r"^disable-model-invocation:\s*true\s*$", fm, re.M) is not None
        m = re.search(r"^description:\s*(.*)$", fm, re.M)
        desc = m.group(1).strip() if m else ""
        if len(desc) > 1 and desc[0] == '"' and desc[-1] == '"':
            desc = desc[1:-1].replace('\\"', '"')
        found[name] = {"user": user, "description": desc}
    return found


def first_sentence(desc):
    m = re.search(r"[.!?](?=\s+[A-Z])", desc)
    sentence = desc[: m.end()] if m else desc
    return sentence.replace("|", "/").strip()


def typed_form(name):
    return TYPED.get(name, f"`/mycelium-extra:{name}`")


def build(skills):
    """Return (markdown, unmapped, missing)."""
    mapped = {n for _, names in GROUPS for n in names}
    unmapped = sorted(n for n, s in skills.items() if s["user"] and n not in mapped and n != ROUTER)
    missing = sorted(n for n in mapped if n not in skills)
    groups = [(title, names) for title, names in GROUPS]
    if unmapped:
        groups.append((OTHER, unmapped))
    out = ["<!-- Generated by scripts/make_router_table.py from skills/*/SKILL.md. Do not edit. -->", ""]
    for title, names in groups:
        rows = [n for n in names if n in skills]
        if not rows:
            continue
        out += [f"## {title}", "", "| Type | What it does |", "|---|---|"]
        out += [f"| {typed_form(n)} | {first_sentence(skills[n]['description'])} |" for n in rows]
        out.append("")
    return "\n".join(out).rstrip() + "\n", unmapped, missing


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", default=".", help="repository root (default: current directory)")
    ap.add_argument("--check", metavar="FILE", help="exit 1 when FILE differs from the generated table")
    args = ap.parse_args()
    skills = read_skills(args.repo)
    if not skills:
        print("no skills/*/SKILL.md under " + args.repo, file=sys.stderr)
        return 2
    text, unmapped, missing = build(skills)
    for name in unmapped:
        print(f"warning: user-invoked skill '{name}' has no group in make_router_table.py; listed under Other", file=sys.stderr)
    for name in missing:
        print(f"warning: group map names '{name}' but skills/{name}/ does not exist; skipped", file=sys.stderr)
    if args.check:
        with open(args.check, encoding="utf-8") as handle:
            current = handle.read()
        if current != text:
            print(f"{args.check} is out of date: regenerate it with this script", file=sys.stderr)
            return 1
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
